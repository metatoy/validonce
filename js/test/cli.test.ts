import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { main } from "../src/cli";

const golden = (n: string) =>
  new URL(`../../conformance/golden/${n}.openapi.json`, import.meta.url)
    .pathname;

function run(argv: string[]) {
  let out = "";
  let err = "";
  const code = main(argv, { out: (s) => (out += s), err: (s) => (err += s) });
  return { code, out, err };
}

const tmp = () => mkdtempSync(join(tmpdir(), "validonce-cli-"));

function rulesOf(file: string) {
  const r = run(["extract", file, "--format", "json"]);
  expect(r.code).toBe(0);
  return JSON.parse(r.out) as Record<
    string,
    { version: number; rules: unknown[] }
  >;
}

describe("extract", () => {
  test("FastAPI and ASP.NET documents give equal Signup rules", () => {
    const a = rulesOf(golden("fastapi"));
    const b = rulesOf(golden("aspnet"));
    expect(a.Signup?.rules.length).toBeGreaterThan(0);
    expect(a.Signup).toEqual(b.Signup);
  });

  test("TypeScript output is deterministic and headed", () => {
    const a = run(["extract", golden("fastapi")]);
    const b = run(["extract", golden("fastapi")]);
    expect(a.out).toBe(b.out);
    expect(a.out).toContain(
      "Generated by `validonce extract` from fastapi.openapi.json",
    );
    expect(a.out).toContain("export const rules = {");
    expect(a.out).toContain("as const satisfies Record<string, RuleSet>;");
    expect(a.out.startsWith("// SPDX-License-Identifier: Apache-2.0\n")).toBe(
      true,
    );
  });

  test("-o writes a file and prints nothing", () => {
    const f = join(tmp(), "rules.gen.ts");
    const r = run(["extract", golden("aspnet"), "-o", f]);
    expect(r).toMatchObject({ code: 0, out: "" });
    expect(readFileSync(f, "utf8")).toContain("Signup");
  });

  test("--schema selects, uses the -Input fallback, and fails on a miss", () => {
    const dir = tmp();
    const doc = join(dir, "doc.json");
    const rs = {
      version: 1,
      rules: [
        {
          id: "A.required_when.b",
          kind: "required_when",
          field: "b",
          when: { present: { field: "a" } },
          message: { key: "k" },
        },
      ],
    };
    writeFileSync(
      doc,
      JSON.stringify({
        components: {
          schemas: {
            "A-Input": { "x-validonce": rs },
            B: { "x-validonce": rs },
          },
        },
      }),
    );
    expect(Object.keys(rulesOf(doc))).toEqual(["A", "B"]);
    const one = run(["extract", doc, "--schema", "A", "--format", "json"]);
    expect(Object.keys(JSON.parse(one.out))).toEqual(["A"]);
    const miss = run(["extract", doc, "--schema", "Nope"]);
    expect(miss.code).toBe(1);
    expect(miss.err).toContain("Nope");
  });
});

describe("exit codes", () => {
  test("1 when no x-validonce", () => {
    const f = join(tmp(), "plain.json");
    writeFileSync(f, JSON.stringify({ components: { schemas: { A: {} } } }));
    expect(run(["extract", f]).code).toBe(1);
  });

  test("2 for usage errors and unreadable input", () => {
    expect(run([]).code).toBe(2);
    expect(run(["bogus"]).code).toBe(2);
    expect(run(["extract"]).code).toBe(2);
    expect(run(["extract", "a.json", "--format", "yaml"]).code).toBe(2);
    expect(run(["extract", "a.json", "--nope"]).code).toBe(2);
    expect(run(["extract", join(tmp(), "missing.json")]).code).toBe(2);
    const bad = join(tmp(), "bad.json");
    writeFileSync(bad, "{not json");
    expect(run(["extract", bad]).code).toBe(2);
  });

  test("--help and --version exit 0", () => {
    expect(run(["--help"])).toMatchObject({ code: 0 });
    expect(run(["--help"]).out).toContain("validonce extract");
    const pkg = JSON.parse(
      readFileSync(new URL("../package.json", import.meta.url), "utf8"),
    ) as { version: string };
    expect(run(["--version"]).out).toBe(`${pkg.version}\n`);
  });
});

const dist = new URL("../dist/cli.js", import.meta.url).pathname;
test.skipIf(!existsSync(dist))("dist/cli.js runs under node", () => {
  const r = spawnSync(
    "node",
    [dist, "extract", golden("fastapi"), "--format", "json"],
    {
      encoding: "utf8",
    },
  );
  expect(r.status).toBe(0);
  expect(JSON.parse(r.stdout).Signup.version).toBe(1);
  expect(readFileSync(dist, "utf8").startsWith("#!/usr/bin/env node\n")).toBe(
    true,
  );
  expect(
    spawnSync("node", [dist, "--version"], { encoding: "utf8" }).stdout,
  ).toMatch(/^\d/);
});
