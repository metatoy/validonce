import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { fileURLToPath } from "node:url";
import { allRulesFromOpenApi } from "./openapi";
import { type RuleSet, ValidonceFormatError } from "./types";

/** Where `main` writes. Defaults to the process streams. */
export interface Io {
  out: (text: string) => void;
  err: (text: string) => void;
}

const HELP = `validonce: extract shared validation rules from an OpenAPI document.

Usage:
  validonce extract <openapi.json> [-o <file>] [--schema <Name>]... [--format ts|json]

Options:
  -o, --out <file>     write to <file> (default: standard output; "-" is also standard output)
  --schema <Name>      only this schema (repeatable). "Name-Input" is used when "Name" has no rules
  --format ts|json     TypeScript module (default) or plain JSON
  -h, --help           show this help
  -v, --version        show the version

Exit codes: 0 done, 1 no x-validonce found, 2 usage error or unreadable input.
`;

function version(): string {
  const url = new URL("../package.json", import.meta.url);
  return (JSON.parse(readFileSync(url, "utf8")) as { version: string }).version;
}

function sortKeys(v: unknown): unknown {
  if (Array.isArray(v)) return v.map(sortKeys);
  if (typeof v === "object" && v !== null) {
    const o = v as Record<string, unknown>;
    return Object.fromEntries(
      Object.keys(o)
        .sort()
        .map((k) => [k, sortKeys(o[k])]),
    );
  }
  return v;
}

/** `Name-Input` is reported as `Name` unless a plain `Name` already exists. */
function collect(doc: unknown, wanted: string[]): Record<string, RuleSet> {
  const all = allRulesFromOpenApi(doc);
  const named: Record<string, RuleSet> = {};
  for (const [name, rs] of Object.entries(all)) {
    const plain = name.endsWith("-Input") ? name.slice(0, -6) : name;
    named[plain !== name && !Object.hasOwn(all, plain) ? plain : name] = rs;
  }
  if (wanted.length === 0) return named;
  const out: Record<string, RuleSet> = {};
  for (const w of wanted)
    if (Object.hasOwn(named, w)) out[w] = named[w] as RuleSet;
  return out;
}

function render(
  sets: Record<string, RuleSet>,
  format: "ts" | "json",
  source: string,
): string {
  const sorted = sortKeys(sets) as Record<string, RuleSet>;
  const names = Object.keys(sorted);
  const body: Record<string, unknown> = {};
  for (const n of names) body[n] = sorted[n];
  const json = JSON.stringify(body, null, 2);
  if (format === "json") return `${json}\n`;
  return [
    "// SPDX-License-Identifier: Apache-2.0",
    "// Copyright 2026 Metatoy LLC",
    "",
    `// Generated by \`validonce extract\` from ${source}. Do not edit; re-run the command.`,
    'import type { RuleSet } from "validonce";',
    "",
    `export const rules = ${json} as const satisfies Record<string, RuleSet>;`,
    "",
  ].join("\n");
}

/**
 * The CLI. Returns the exit code (0, 1 or 2); never calls `process.exit`.
 * Nothing is written when the code is not 0.
 */
export function main(argv: readonly string[], io?: Partial<Io>): number {
  const out = io?.out ?? ((s: string) => void process.stdout.write(s));
  const err = io?.err ?? ((s: string) => void process.stderr.write(s));
  const usage = (msg: string): number => {
    err(`validonce: ${msg}\nTry "validonce --help".\n`);
    return 2;
  };

  const args = [...argv];
  if (args.length === 0) return usage("missing command");
  if (args[0] === "-h" || args[0] === "--help") {
    out(HELP);
    return 0;
  }
  if (args[0] === "-v" || args[0] === "--version") {
    out(`${version()}\n`);
    return 0;
  }
  if (args[0] !== "extract") return usage(`unknown command "${args[0]}"`);
  args.shift();

  let file: string | undefined;
  let outFile: string | undefined;
  let format: "ts" | "json" = "ts";
  const schemas: string[] = [];
  for (let i = 0; i < args.length; i++) {
    const a = args[i] as string;
    if (a === "-h" || a === "--help") {
      out(HELP);
      return 0;
    }
    if (a === "-o" || a === "--out" || a === "--schema" || a === "--format") {
      const v = args[++i];
      if (v === undefined) return usage(`${a} needs a value`);
      if (a === "--schema") schemas.push(v);
      else if (a === "--format") {
        if (v !== "ts" && v !== "json")
          return usage(`--format must be ts or json, not "${v}"`);
        format = v;
      } else outFile = v;
    } else if (a.startsWith("-") && a !== "-") {
      return usage(`unknown option "${a}"`);
    } else if (file === undefined) file = a;
    else return usage(`unexpected argument "${a}"`);
  }
  if (file === undefined) return usage("extract needs an OpenAPI file");

  let doc: unknown;
  try {
    doc = JSON.parse(readFileSync(file, "utf8"));
  } catch (e) {
    return usage(
      `cannot read ${file}: ${e instanceof Error ? e.message : String(e)}`,
    );
  }

  let sets: Record<string, RuleSet>;
  try {
    sets = collect(doc, schemas);
  } catch (e) {
    if (e instanceof ValidonceFormatError) {
      err(`validonce: invalid x-validonce in ${file}: ${e.message}\n`);
      return 2;
    }
    throw e;
  }
  const missing = schemas.filter((s) => !Object.hasOwn(sets, s));
  if (missing.length > 0) {
    err(
      `validonce: no x-validonce found for ${missing.join(", ")} in ${file}\n`,
    );
    return 1;
  }
  if (Object.keys(sets).length === 0) {
    err(`validonce: no x-validonce found in ${file}\n`);
    return 1;
  }

  const text = render(sets, format, basename(file));
  if (outFile === undefined || outFile === "-") out(text);
  else {
    try {
      writeFileSync(outFile, text);
    } catch (e) {
      return usage(
        `cannot write ${outFile}: ${e instanceof Error ? e.message : String(e)}`,
      );
    }
  }
  return 0;
}

function isEntry(): boolean {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return realpathSync(entry) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isEntry()) process.exitCode = main(process.argv.slice(2));
